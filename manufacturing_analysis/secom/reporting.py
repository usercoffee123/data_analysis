"""Markdown reports of SECOM evidence and optional model commentary."""

from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

from manufacturing_analysis.common.io import write_text


def _table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> list[str]:
    """Escape table cells so model text and feature names cannot break columns."""
    def cell(value: Any) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    return [
        " | ".join(headers),
        " | ".join("---" for _ in headers),
        *(" | ".join(cell(value) for value in row) for row in rows),
    ]


def _input_lines(manifest: dict[str, Any]) -> list[str]:
    lines = [
        "# SECOM analysis report", "",
        f"Status: **{manifest['status']}**",
        f"Created: {manifest['created_at']}",
        f"Model: {manifest['model']}", "",
        f"Source: {manifest['source']}", "",
        "## Input verification", "",
    ]
    for item in manifest["inputs"]:
        lines.extend([
            f"- File: {item['file']}",
            f"  - SHA-256: `{item['sha256']}`",
            f"  - Verified: {item['digest_verified']}",
        ])
    if "error" in manifest:
        lines.extend(["", "## Processing error", "", str(manifest["error"])])
    return lines


def _llm_lines(analysis: dict[str, Any]) -> list[str]:
    status = analysis.get("status", "success" if analysis else "skipped")
    lines = ["", "## LLM output", "", f"LLM commentary status: **{status}**", ""]
    if status != "success":
        lines.append(str(analysis.get("summary", "No LLM commentary was generated.")))
        if analysis.get("error"):
            lines.extend(["", str(analysis["error"])])
        return lines

    lines.extend([
        "The following interpretation was generated by the model. Sample flags and briefs come from Python screening rules.",
        "Model commentary is unverified; use the independent screening evaluation table below for measured counts and recall. This fixed-threshold run reports descriptive results for the input records.",
        "", "### Summary", "", str(analysis.get("summary", "No summary returned.")),
        "", "### Observations", "",
    ])
    for observation in analysis.get("observations", []):
        if isinstance(observation, dict):
            lines.append(
                f"- {observation.get('sensor_id', 'Observation')}: "
                f"{observation.get('interpretation', '')} "
                f"(model-reported confidence: {observation.get('confidence', 'unspecified')})"
            )
        else:
            lines.append(f"- {observation}")
    lines.extend(["", "### Limitations", "", str(analysis.get("limitations", ""))])
    return lines


def _evaluation_lines(evaluation: dict[str, Any]) -> list[str]:
    metric_keys = (
        "sample_count", "independent_flags", "failures_captured",
        "failures_missed", "passing_records_flagged",
    )
    rows = [
        [name, *(metrics[key] for key in metric_keys)]
        for name, metrics in evaluation.items()
        if metrics["sample_count"] > 0
    ]
    lines = [
        "", "### Independent screening evaluation", "",
        "Known failed-test flags are excluded from these detection metrics.", "",
    ]
    lines.extend(_table([
        "Cohort", "Records", "Independent flags", "Failures captured",
        "Failures missed", "Passing records flagged",
    ], rows))
    if evaluation.get("held_out", {}).get("sample_count", 0) == 0:
        lines.extend([
            "",
            "No held-out evaluation is reported for this run. All-record results are descriptive and may include records used to fit the saved thresholds.",
        ])
    return lines


def _screening_lines(screening: dict[str, Any]) -> list[str]:
    lines = [
        "", "## Sample screening", "",
        f"Screened **{screening['sample_count']}** samples; flagged **{screening['flagged_count']}**.", "",
    ]
    lines.extend(_table(["Flag reason", "Records"], screening["reason_counts"].items()))
    lines.extend([
        "", "Reason counts overlap. Statistical flags do not establish defects.",
        "", "### Screening method", "",
    ])
    lines.extend(f"- {key}: {value}" for key, value in screening["method"].items())
    lines.extend(_evaluation_lines(screening["evaluation"]))
    return lines


def render_summary(manifest: dict[str, Any]) -> str:
    """Render run metadata, aggregate evidence, and LLM commentary without briefs."""
    lines = _input_lines(manifest)
    assessment = manifest.get("assessment")
    if assessment:
        lines.extend([
            "", "## What happened", "", assessment["description"],
            "", "## Recommendations", "",
        ])
        lines.extend(f"- {step}" for step in assessment["recommendations"])
        lines.extend(_llm_lines(assessment.get("model_analysis", {})))
        lines.extend(_screening_lines(assessment["sample_screening"]))
    return "\n".join(lines).rstrip() + "\n"


def _brief_lines(brief: dict[str, Any]) -> list[str]:
    lines = [
        f"### {brief['sample_id']} — source row {brief['source_line']}", "",
        f"Timestamp: {brief['timestamp']}", "",
        f"Flag reasons: {', '.join(brief['flag_reasons'])}", "",
        brief["description"], "", "Recommendations:", "",
    ]
    lines.extend(f"- {step}" for step in brief["recommendations"])
    if brief["unusual_features"]:
        feature_keys = ("feature_id", "value", "reference_min", "reference_max", "direction")
        rows = [[feature[key] for key in feature_keys] for feature in brief["unusual_features"]]
        lines.append("")
        lines.extend(_table([
            "Feature", "Value", "Reference minimum", "Reference maximum", "Direction",
        ], rows))
    missing = ", ".join(brief["missing_features"]) or "None"
    lines.extend(["", f"Missing features: {missing}", ""])
    return lines


def render_flagged_briefs(manifest: dict[str, Any]) -> str:
    """Render per-record investigation evidence for the full report."""
    assessment = manifest.get("assessment")
    if not assessment:
        return ""
    lines = ["## Flagged sample briefs", ""]
    for brief in assessment["sample_screening"]["flagged_sample_briefs"]:
        lines.extend(_brief_lines(brief))
    return "\n".join(lines).rstrip() + "\n"


def write_markdown_report(manifest: dict[str, Any], path: Path) -> None:
    """Write short and full reports from saved results, without another LLM call."""
    summary = render_summary(manifest)
    briefs = render_flagged_briefs(manifest)
    full_report = summary + ("\n" + briefs if briefs else "")
    summary_path = path.with_name(path.stem + ".summary.md")
    write_text(summary_path, summary + f"\nFull sample briefs: [{path.name}]({path.name})\n")
    write_text(path, full_report)
