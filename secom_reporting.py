"""Markdown presentation of SECOM evidence and optional model commentary."""

from pathlib import Path
from typing import Any


def write_markdown_report(manifest: dict[str, Any], path: Path) -> None:
    """Render saved evidence and model output without making another LLM call."""
    def cell(value: Any) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    lines = ["# SECOM analysis report", "", f"Status: **{manifest['status']}**",
             f"Created: {manifest['created_at']}", f"Model: {manifest['model']}", "",
             f"Source: {manifest['source']}", "", "## Input verification", ""]
    for item in manifest["inputs"]:
        lines.extend([f"- File: {item['file']}",
                      f"  - SHA-256: `{item['sha256']}`",
                      f"  - Verified: {item['digest_verified']}"])
    if "error" in manifest:
        lines.extend(["", "## Processing error", "", manifest["error"]])
    assessment = manifest.get("assessment")
    if assessment:
        lines.extend(["", "## What happened", "", assessment["description"],
                      "", "## Recommendations", ""])
        lines.extend(f"- {step}" for step in assessment["recommendations"])
        analysis = assessment.get("model_analysis", {})
        lines.extend(["", f"LLM commentary status: **{analysis.get('status', 'success')}**"])
        if analysis.get("error"):
            lines.extend(["", str(analysis["error"])])
        lines.extend(["", "## LLM output", "",
                      "The following interpretation was generated by the model. Sample flags and briefs come from Python screening rules.",
                      "Model commentary is unverified; use the independent screening evaluation table below for measured counts and recall. This fixed-threshold run reports descriptive results for the input records.",
                      "", "### Summary", "", str(analysis.get("summary", "No summary returned.")),
                      "", "### Observations", ""])
        for observation in analysis.get("observations", []):
            if isinstance(observation, dict):
                lines.append(f"- {observation.get('sensor_id', 'Observation')}: "
                             f"{observation.get('interpretation', '')} "
                             f"(model-reported confidence: {observation.get('confidence', 'unspecified')})")
            else:
                lines.append(f"- {observation}")
        lines.extend(["", "### Limitations", "", str(analysis.get("limitations", ""))])
        screening = assessment["sample_screening"]
        lines.extend(["", "## Sample screening", "",
                      f"Screened **{screening['sample_count']}** samples; flagged **{screening['flagged_count']}**.", "",
                      "Flag reason | Records", "--- | ---"])
        lines.extend(f"{reason} | {count}" for reason, count in screening["reason_counts"].items())
        lines.extend(["", "Reason counts overlap. Statistical flags do not establish defects.", "",
                      "### Screening method", ""])
        lines.extend(f"- {key}: {value}" for key, value in screening["method"].items())
        lines.extend(["", "### Independent screening evaluation", "",
                      "Known failed-test flags are excluded from these detection metrics.", "",
                      "Cohort | Records | Independent flags | Failures captured | Failures missed | Passing records flagged",
                      "--- | --- | --- | --- | --- | ---"])
        for name, metrics in screening["evaluation"].items():
            if name == "held_out" and metrics["sample_count"] == 0:
                continue
            lines.append(" | ".join([name] + [cell(metrics[key]) for key in (
                "sample_count", "independent_flags", "failures_captured", "failures_missed", "passing_records_flagged")]))
        if screening["evaluation"]["held_out"]["sample_count"] == 0:
            lines.extend(["", "No held-out evaluation is reported for this run. All-record results are descriptive and may include records used to fit the saved thresholds."])
        lines.extend(["", "## Flagged sample briefs", ""])
        for brief in screening["flagged_sample_briefs"]:
            lines.extend([f"### {brief['sample_id']} — source row {brief['source_line']}", "",
                          f"Timestamp: {brief['timestamp']}", "",
                          f"Flag reasons: {', '.join(brief['flag_reasons'])}", "",
                          brief["description"], "", "Recommendations:", ""])
            lines.extend(f"- {step}" for step in brief["recommendations"])
            if brief["unusual_features"]:
                lines.extend(["", "Feature | Value | Reference minimum | Reference maximum | Direction",
                              "--- | --- | --- | --- | ---"])
                for feature in brief["unusual_features"]:
                    lines.append(" | ".join(cell(feature[key]) for key in (
                        "feature_id", "value", "reference_min", "reference_max", "direction")))
            lines.extend(["", "Missing features: " + (", ".join(brief["missing_features"]) or "None"), ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    path.write_text(text, encoding="utf-8")
    summary = text.split("## Flagged sample briefs", 1)[0].rstrip() + "\n"
    summary += f"\nFull sample briefs: [{path.name}]({path.name})\n"
    path.with_name(path.stem + ".summary.md").write_text(summary, encoding="utf-8")

